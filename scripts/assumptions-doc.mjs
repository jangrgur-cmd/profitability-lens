// assumptions-doc.mjs: renders docs/assumptions.md from the messaging case
// study's data/assumptions.json, so the document can never drift from the
// numbers the dashboard uses. Pure function; the CLI is build-assumptions-doc.mjs.

import { STEPS } from "../modules/messaging/js/scenarios.js";

const STATUS_LABELS = { sourced: "Sourced", estimated: "Estimated", placeholder: "Placeholder" };

/** Escapes text for a Markdown table cell. */
function cell(text) {
  return String(text ?? "").replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}

/** Shows a value as stored, without floating-point noise (same rule as the Assumptions tab). */
function showValue(value) {
  return typeof value === "number" ? String(Number(value.toPrecision(6))) : String(value);
}

/** Link to a source page, labelled with its site name; "—" when there is none. */
function sourceLink(url) {
  if (!url) return "—";
  return `[${new URL(url).hostname.replace(/^www\./, "")}](${url})`;
}

/** GitHub-style heading anchor. */
function anchor(heading) {
  return heading.toLowerCase().replace(/[^\p{L}\p{N} -]/gu, "").replace(/ /g, "-");
}

/** Joins Markdown table rows. */
function table(header, rows) {
  return [`| ${header.join(" | ")} |`, `|${header.map(() => "---").join("|")}|`, ...rows.map((r) => `| ${r.map(cell).join(" | ")} |`)].join("\n");
}

/**
 * Renders the full assumptions document.
 * @param {object} file parsed modules/messaging/data/assumptions.json
 * @returns {string} Markdown text ending in a newline
 */
export function renderAssumptionsDoc(file) {
  const { meta, assumptions, customers, generator, dimensions } = file;
  const groups = [...new Set(assumptions.map((a) => a.group))];
  const countByStatus = (status) => assumptions.filter((a) => a.status === status).length;
  const countryName = Object.fromEntries(dimensions.countries.map((c) => [c.code, c.name]));
  const statusSummary = Object.keys(STATUS_LABELS)
    .map((s) => [STATUS_LABELS[s], countByStatus(s)])
    .filter(([, n]) => n > 0)
    .map(([label, n]) => `${n} ${label.toLowerCase()}`)
    .join(", ");

  const parts = [
    "# Messaging case study: assumptions",
    "",
    "<!-- Generated by scripts/build-assumptions-doc.mjs from modules/messaging/data/assumptions.json. Do not edit by hand. -->",
    "",
    `> ${meta.disclaimer}`,
    "",
    `Every number the [messaging dashboard](../modules/messaging/) uses is listed below: **${assumptions.length} assumptions** (${statusSummary}) and **${customers.length} illustrative customer archetypes**. The same list, with filters and CSV export, is on the dashboard's **Assumptions & method** tab.`,
    "",
    "- **Sourced:** read on the public page linked in *Source*; any conversion (for example USD → EUR) is explained in *Note*.",
    "- **Estimated:** no public figure exists; *Note* gives the reasoning.",
    "",
    "## Contents",
    "",
    ...groups.map((g) => `- [${g}](#${anchor(g)}) (${assumptions.filter((a) => a.group === g).length})`),
    "- [Customer archetypes](#customer-archetypes)",
    "- [Generator parameters](#generator-parameters)",
    "- [Scenario order of operations](#scenario-order-of-operations)",
  ];

  for (const group of groups) {
    const rows = assumptions
      .filter((a) => a.group === group)
      .map((a) => [`\`${a.id}\``, a.label, showValue(a.value), a.unit, STATUS_LABELS[a.status] ?? a.status, sourceLink(a.source), a.note]);
    parts.push("", `## ${group}`, "", table(["ID", "Assumption", "Value", "Unit", "Status", "Source", "Note"], rows));
  }

  const customerRows = customers.map((c) => [
    c.id,
    c.name,
    c.industry,
    countryName[c.home_country] ?? c.home_country,
    c.size_tier,
    c.base_monthly_volume.toLocaleString("en-US"),
    c.discount_tier,
    c.volume_note,
  ]);
  parts.push(
    "",
    "## Customer archetypes",
    "",
    "Fictional archetypes, not real companies. Volumes are estimates; the discount tier refers to the *Volume discount* assumptions above.",
    "",
    table(["ID", "Archetype", "Industry", "Home country", "Size", "Base monthly volume", "Discount tier", "How the volume was estimated"], customerRows),
  );

  const generatorRows = Object.entries(generator).map(([key, value]) => [`\`${key}\``, typeof value === "object" ? JSON.stringify(value) : showValue(value)]);
  parts.push(
    "",
    "## Generator parameters",
    "",
    "Used by `modules/messaging/scripts/generate-data.mjs`, which turns the assumptions above into `traffic.json` with a seeded random-number generator, so the same inputs always give the same data.",
    "",
    table(["Parameter", "Value"], generatorRows),
  );

  parts.push(
    "",
    "## Scenario order of operations",
    "",
    "What-if scenarios apply their steps in this fixed order; each step's effect in the margin bridge is gross profit after the step minus gross profit before it.",
    "",
    ...STEPS.map((s, i) => `${i + 1}. **${s.label}:** ${s.description}`),
  );

  return parts.join("\n") + "\n";
}
